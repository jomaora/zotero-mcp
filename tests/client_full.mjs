import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
const port = process.argv[2];
const t = new StdioClientTransport({ command: "node", args: [fileURLToPath(new URL("../server/index.js", import.meta.url))], env: { ...process.env, ZOTERO_LOCAL_PORT: port, HTTP_PROXY: "http://127.0.0.1:9", HTTPS_PROXY: "http://127.0.0.1:9" } });
const c = new Client({ name: "test", version: "0" });
await c.connect(t);
const show = (label, r) => console.log(`\n### ${label}${r.isError ? "  [isError]" : ""}\n` + r.content.map((x) => x.text).join("\n").slice(0, 700));
const tools = await c.listTools();
console.log("TOOLS:", tools.tools.map((x) => `${x.name}(readOnly=${x.annotations?.readOnlyHint})`).join(", "));
const call = (name, args) => c.callTool({ name, arguments: args });
show("search ok", await call("zotero_search", { query: "Trigger Aataentsic" }));
show("search none", await call("zotero_search", { query: "Inexistant" }));
show("search type", await call("zotero_search", { query: "Trigger", item_type: "book", qmode: "everything" }));
show("get_item", await call("zotero_get_item", { item_key: "YPLGMC2X" }));
show("children", await call("zotero_children", { item_key: "YPLGMC2X" }));
const n0 = await call("zotero_get_note", { note_key: "943XCP8U" });
show("note offset 0", n0);
const m = n0.content[0].text.match(/suite : offset=(\d+)/);
if (m) show("note suite", await call("zotero_get_note", { note_key: "943XCP8U", offset: Number(m[1]), max_chars: 1000 }));
show("annotations", await call("zotero_annotations", { attachment_key: "ATTACH01" }));
show("clé minuscule ok", await call("zotero_get_item", { item_key: "yplgmc2x" }));
show("clé invalide", await call("zotero_get_item", { item_key: "../../etc" }).catch((e) => ({ isError: true, content: [{ text: "REJET SDK: " + e.message }] })));
show("get_note sur un livre", await call("zotero_get_note", { note_key: "YPLGMC2X" }));
show("clé inconnue", await call("zotero_get_item", { item_key: "ZZZZZZZZ" }));
show("item_type invalide", await call("zotero_search", { query: "x", item_type: "book;rm" }));
await c.close();
